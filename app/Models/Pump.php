<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\SoftDeletes;

class Pump extends Model
{
    use HasFactory, SoftDeletes;

    protected $fillable = [
        'name',
        'code',
        'nozzle_number',
        'meter_type',
        'product_id',
        'tank_no',
        'initial_reading',
        'last_reading',
        'status',
        'description',
    ];

    protected $casts = [
        'initial_reading' => 'decimal:2',
        'last_reading'    => 'decimal:2',
    ];

    /**
     * Relationship to the dispensed fuel product
     */
    public function product()
    {
        return $this->belongsTo(Product::class);
    }

    /**
     * Relationship to shift closings where this pump machine was used
     */
    public function shiftClosings()
    {
        return $this->hasMany(ShiftClosing::class);
    }

    /**
     * Relationship to meter reading audit log records
     */
    public function meterReadings()
    {
        return $this->hasMany(PumpMeterReading::class)->latest('id');
    }

    /**
     * Purchases delivered into this pump's dedicated tank/dispenser
     */
    public function purchases()
    {
        return $this->hasMany(Purchase::class);
    }

    /**
     * Active scope
     */
    public function scopeActive($query)
    {
        return $query->where('status', 'active');
    }

    /**
     * Status badge with color codes
     */
    public function getStatusBadgeAttribute(): string
    {
        return match ($this->status) {
            'active' => '<span class="badge bg-success-subtle text-success border border-success-subtle px-2 py-0.5 rounded-pill"><i class="bi bi-check-circle me-1"></i>Active</span>',
            'maintenance' => '<span class="badge bg-warning-subtle text-warning border border-warning-subtle px-2 py-0.5 rounded-pill"><i class="bi bi-tools me-1"></i>Maintenance</span>',
            default => '<span class="badge bg-secondary-subtle text-secondary border border-secondary-subtle px-2 py-0.5 rounded-pill"><i class="bi bi-pause-circle me-1"></i>Inactive</span>',
        };
    }

    /**
     * Calculate cumulative total fuel dispensed through this pump machine (in liters)
     */
    public function getTotalDispensedLitersAttribute(): float
    {
        return (float) $this->shiftClosings()->sum('total_liters');
    }

    /**
     * Calculate cumulative sales amount generated by this pump (in Rs.)
     */
    public function getTotalSalesAmountAttribute(): float
    {
        return (float) $this->shiftClosings()->sum('total_sale');
    }

    /**
     * Liters dispensed today
     */
    public function getDispensedTodayAttribute(): float
    {
        return (float) $this->shiftClosings()->whereDate('date', now()->toDateString())->sum('total_liters');
    }

    /**
     * Get stock synchronization details with linked Product and Purchases
     */
    public function getStockSyncData(): array
    {
        $product = $this->product;
        if (!$product) {
            return [
                'has_product' => false,
                'product_name' => 'Unassigned',
                'current_stock' => 0,
                'unit' => 'Liter',
                'fuel_rate' => 0,
                'total_purchased' => 0,
                'total_dispensed_all_pumps' => 0,
                'this_pump_dispensed' => 0,
                'tank_or_shelf' => $this->tank_no ?: 'N/A',
            ];
        }

        $totalPurchased = (float) Purchase::where('product_id', $product->id)->sum('quantity');
        $totalDispensedAll = (float) ShiftClosing::where('product_id', $product->id)->sum('total_liters');
        $thisPumpDispensed = (float) $this->shiftClosings()->sum('total_liters');

        return [
            'has_product' => true,
            'product_id' => $product->id,
            'product_name' => $product->name,
            'category' => $product->category,
            'current_stock' => (float) $product->current_stock,
            'opening_stock' => (float) $product->opening_stock,
            'unit' => $product->unit_label,
            'fuel_rate' => (float) $product->sale_price,
            'purchase_price' => (float) $product->purchase_price,
            'total_purchased' => $totalPurchased,
            'total_dispensed_all_pumps' => $totalDispensedAll,
            'this_pump_dispensed' => $thisPumpDispensed,
            'tank_or_shelf' => $this->tank_no ?: ($product->tank_or_shelf ?: 'Storage Tank'),
        ];
    }
}
